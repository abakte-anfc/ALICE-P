import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('dist/index.html','utf8');
for(const key of ['og:title','og:description','og:url','og:image','og:image:width','og:image:height','twitter:card'])assert(html.includes(key),`Metadado ausente: ${key}`);
assert(!html.includes('__SITE_URL__'),'URL de compartilhamento não resolvida');
const image=html.match(/property="og:image" content="([^"]+)/)?.[1];
assert(image,'Imagem de compartilhamento ausente');
assert.equal(new URL(image).protocol,'https:');
assert(fs.existsSync('dist/projeto-frida-social.jpg'));
assert(html.includes('content="1200"')&&html.includes('content="630"'));
console.log('Metadados presentes no HTML estático; imagem disponível no build:',image);
